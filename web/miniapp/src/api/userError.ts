import { ApiError } from './client';

const statusMessages: Partial<Record<number, string>> = {
  401: 'Сессия завершилась. Откройте мини-приложение в MAX ещё раз.',
  403: 'Недостаточно прав для этого действия.',
  404: 'Объект недоступен или был удалён.',
  409: 'Данные уже изменились или операция больше недоступна. Обновите экран и повторите попытку.',
  413: 'Файл слишком большой. Выберите файл меньшего размера.',
  429: 'Слишком много запросов. Подождите немного и попробуйте снова.',
  502: 'Сервис временно недоступен. Повторите попытку позже.',
  503: 'Сервис временно недоступен. Повторите попытку позже.',
  504: 'Сервис отвечает слишком долго. Повторите попытку позже.',
};

export const userErrorMessage = (
  cause: unknown,
  fallback = 'Не удалось выполнить действие. Проверьте подключение и повторите попытку.',
) => {
  if (cause instanceof ApiError) return statusMessages[cause.status] ?? fallback;
  if (cause instanceof TypeError) {
    return 'Нет соединения с сервисом. Проверьте интернет и повторите попытку.';
  }
  return fallback;
};
